/** @type {import('next').NextConfig} */

// Restrictive by default. The browser only ever talks to our own origin — the metals
// API is proxied server-side so its key never reaches the client.
//
// Accepted trade-off: 'unsafe-inline' on script-src. Next's hydration bootstrap is an
// inline script, so removing it means threading a per-request nonce through middleware
// and the layout. Given this site renders zero user-generated content, the XSS surface
// it would defend is currently empty. Revisit if that ever stops being true.
const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  "frame-ancestors 'none'",
  "form-action 'self'",
  "base-uri 'self'",
  "object-src 'none'",
].join("; ");

const nextConfig = {
  reactStrictMode: true,
  async headers() {
    return [
      {
        source: "/(.*)",
        headers: [
          { key: "Content-Security-Policy", value: csp },
          { key: "X-Frame-Options", value: "DENY" },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          {
            key: "Strict-Transport-Security",
            value: "max-age=63072000; includeSubDomains; preload",
          },
        ],
      },
    ];
  },
};

export default nextConfig;
